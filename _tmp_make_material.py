# --- pack URP Lit mask: R = metallic, A = smoothness (1 - roughness) ---
metal = np.array(Image.open(os.path.join(TEX, 'dungeon_arch_metal.tga.png')).convert('L'))
rough = np.array(Image.open(os.path.join(TEX, 'dungeon_arch_rough.tga.png')).convert('L'))
assert metal.shape == rough.shape == (2048, 2048), (metal.shape, rough.shape)

mask = np.zeros((2048, 2048, 4), dtype=np.uint8)
mask[:, :, 0] = metal                      # R = metallic
mask[:, :, 1] = 0                          # unused (was AO)
mask[:, :, 2] = 0                          # unused
mask[:, :, 3] = (255 - rough)              # A = smoothness
# fully opaque RGB channels where unused, so nothing odd leaks when sampled
mask[:, :, 1] = 255
mask[:, :, 2] = 255

mask_path = os.path.join(TEX, 'dungeon_arch_mask.png')
Image.fromarray(mask, 'RGBA').save(mask_path)
print('wrote', mask_path)

